    public static function markup(string $nama): string
    {
        return self::GARIS[$nama] ?? self::GARIS['book-open'];
    }

    /**
     * Pilih ikon yang cocok untuk nama kategori; bawaannya buku terbuka.
     */
    public static function untukKategori(string $namaKategori): string
    {
        $nama = mb_strtolower($namaKategori);

        if (preg_match('/^ai\b/u', $nama)) {
            return 'cpu';
        }

        foreach (self::KATEGORI as $kata => $ikon) {
            if (str_contains($nama, $kata)) {
                return $ikon;
            }
        }

        return 'book-open';
    }
